package it.unisa.ocelot.simulator;

import java.util.List;

import it.unisa.ocelot.c.cfg.edges.LabeledEdge;
import it.unisa.ocelot.c.cfg.nodes.CFGNode;

public interface SimulatorListener {
	/**
	 * Visits a flow edge.
	 * 
	 * @param pEdge the visited {@link LabeledEdge}.
	 */
	public void onEdgeVisit(LabeledEdge pEdge);
	
	/**
	 * Visits a branch edge in an if statement.
	 * 
	 * @param pEdge the visited {@link LabeledEdge}.
	 * @param pIfEvent the {@link IfExecutionEvent}
	 *        associated to {@code pEdge}.
	 */
	public void onEdgeVisit(LabeledEdge pEdge, IfExecutionEvent pIfEvent);
	
	/**
	 * Visits a branch edge in a switch statement.
	 * 
	 * @param pEdge the visited {@link LabeledEdge}.
	 * @param pCaseEvent the {@link CaseExecutionEvent}
	 *        associated to {@code pEdge}.
	 * @param pCaseEvents a {@link List}{@code <}{@link CaseExecutionEvent}{@code >}
	 *        containing all the events generated by the execution of the 
	 *        switch statement. 
	 */
	public void onEdgeVisit(LabeledEdge pEdge, CaseExecutionEvent pCaseEvent, List<CaseExecutionEvent> pCaseEvents);
	
	/**
	 * Visits a node.
	 * 
	 * @param pNode a {@link CFGNode}.
	 */
	public void onNodeVisit(CFGNode pNode);
}
